import Foundation

/// Pano geçmişindeki bir öğe. Değer tipi; resimler diskte (Application Support) dosya olarak tutulur.
struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable, CaseIterable, Identifiable {
        case text, link, media
        var id: String { rawValue }
        var title: String {
            switch self {
            case .text: return "Yazı"
            case .link: return "Bağlantı"
            case .media: return "Medya"
            }
        }
        var symbol: String {
            switch self {
            case .text: return "text.alignleft"
            case .link: return "link"
            case .media: return "photo"
            }
        }
    }

    let id: UUID
    let kind: Kind
    /// Yazı / bağlantı içeriği ya da dosya yolları (satır satır).
    let text: String?
    /// Kopyalanan resmin diskteki dosya adı (yalnızca `media`).
    let imageFile: String?
    let date: Date
    let sourceApp: String?
    var isStarred: Bool

    func with(starred: Bool) -> ClipboardItem {
        var copy = self
        copy.isStarred = starred
        return copy
    }

    /// Aynı içerik mi? (Tekrar kopyalanınca yeni kayıt açılmaz, öne alınır.)
    func hasSameContent(as other: ClipboardItem) -> Bool {
        kind == other.kind && text == other.text && (kind != .media || text != nil || imageFile == other.imageFile)
    }
}

enum ClipboardFilter: Equatable {
    case all
    case starred
    case kind(ClipboardItem.Kind)
}

/// Saf pano mantığı (test edilir).
enum ClipboardLogic {
    static let maxItems = 200
    /// Yıldızlılar dahil mutlak üst sınır (disk büyümesi sınırsız olmasın).
    static let maxTotalItems = 500
    static let maxTextLength = 20_000

    /// Metni sınıflandırır: tek satırlık http(s) adresi → bağlantı, değilse yazı.
    static func classify(_ text: String) -> ClipboardItem.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isNewline), !trimmed.contains(" "),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              ["http", "https"].contains(scheme), url.host != nil else { return .text }
        return .link
    }

    /// Yeni öğeyi başa ekler; aynı içerik varsa onu (yıldızını koruyarak) öne taşır.
    /// Sınır aşılırsa en eski **yıldızsız** öğeler düşer; yıldızlılar asla silinmez.
    static func adding(_ item: ClipboardItem, to items: [ClipboardItem]) -> (items: [ClipboardItem], removed: [ClipboardItem]) {
        var rest = items
        var incoming = item
        if let index = rest.firstIndex(where: { $0.hasSameContent(as: item) }) {
            incoming = item.with(starred: rest[index].isStarred)
            rest.remove(at: index)
        }
        var result = [incoming] + rest
        var removed: [ClipboardItem] = []
        while result.count > maxItems, let index = result.lastIndex(where: { !$0.isStarred }) {
            removed.append(result.remove(at: index))
        }
        // Yalnızca yıldızlılarla bile sınır aşılırsa en eski yıldızlılar düşer.
        while result.count > maxTotalItems {
            removed.append(result.removeLast())
        }
        return (result, removed)
    }

    static func filtered(_ items: [ClipboardItem], by filter: ClipboardFilter, query: String) -> [ClipboardItem] {
        let byFilter: [ClipboardItem]
        switch filter {
        case .all: byFilter = items
        case .starred: byFilter = items.filter(\.isStarred)
        case .kind(let kind): byFilter = items.filter { $0.kind == kind }
        }
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return byFilter }
        return byFilter.filter { ($0.text ?? "").localizedCaseInsensitiveContains(q) }
    }

    /// Parola yöneticileri bu türleri işaretler: kaydetmeyiz (nspasteboard.org kuralları).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    static func shouldIgnore(types: [String]) -> Bool {
        !ignoredTypes.isDisjoint(with: types)
    }
}
